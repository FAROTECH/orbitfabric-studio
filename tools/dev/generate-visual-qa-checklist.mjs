#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const repoRoot = process.cwd();
const manifestPath = path.join(repoRoot, "src", "devSurfaceCaptureManifest.ts");
const checklistPath = path.join(repoRoot, "docs", "qa", "visual-qa-capture-checklist.md");

const args = new Set(process.argv.slice(2));
const shouldWrite = args.has("--write");
const shouldCheck = args.has("--check");

if (!existsSync(manifestPath)) {
  throw new Error(`Capture manifest not found: ${manifestPath}`);
}

const manifestSource = readFileSync(manifestPath, "utf8");

function extractExportedConstArray(source, constName) {
  const marker = `export const ${constName}`;
  const markerIndex = source.indexOf(marker);

  if (markerIndex < 0) {
    throw new Error(`Missing manifest export: ${constName}`);
  }

  const equalsIndex = source.indexOf("=", markerIndex);
  if (equalsIndex < 0) {
    throw new Error(`Missing initializer for manifest export: ${constName}`);
  }

  const openIndex = source.indexOf("[", equalsIndex);
  if (openIndex < 0) {
    throw new Error(`Missing array initializer for manifest export: ${constName}`);
  }

  let depth = 0;
  let quote = null;
  let escaped = false;
  let lineComment = false;
  let blockComment = false;

  for (let i = openIndex; i < source.length; i += 1) {
    const char = source[i];
    const next = source[i + 1];

    if (lineComment) {
      if (char === "\n") {
        lineComment = false;
      }
      continue;
    }

    if (blockComment) {
      if (char === "*" && next === "/") {
        blockComment = false;
        i += 1;
      }
      continue;
    }

    if (quote) {
      if (escaped) {
        escaped = false;
        continue;
      }

      if (char === "\\") {
        escaped = true;
        continue;
      }

      if (char === quote) {
        quote = null;
      }
      continue;
    }

    if (char === "/" && next === "/") {
      lineComment = true;
      i += 1;
      continue;
    }

    if (char === "/" && next === "*") {
      blockComment = true;
      i += 1;
      continue;
    }

    if (char === '"' || char === "'" || char === "`") {
      quote = char;
      continue;
    }

    if (char === "[") {
      depth += 1;
      continue;
    }

    if (char === "]") {
      depth -= 1;
      if (depth === 0) {
        return source.slice(openIndex, i + 1);
      }
    }
  }

  throw new Error(`Unterminated array initializer for manifest export: ${constName}`);
}

function evaluateArrayLiteral(arrayLiteral, constName) {
  try {
    return Function(`"use strict"; return (${arrayLiteral});`)();
  } catch (error) {
    throw new Error(`Failed to evaluate manifest array ${constName}: ${error.message}`);
  }
}

function extractManifestVersion(source) {
  const match = source.match(/export\s+const\s+DEV_SURFACE_CAPTURE_MANIFEST_VERSION\s*=\s*["']([^"']+)["']/);
  return match ? match[1] : "unknown";
}

function escapeMarkdown(value) {
  return String(value ?? "")
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ")
    .trim();
}

function code(value) {
  return `\`${String(value ?? "").replaceAll("`", "\\`")}\``;
}

function renderChecklist({ version, profiles, targets }) {
  const profileById = new Map(profiles.map((profile) => [profile.id, profile]));
  const generatedAt = new Date().toISOString();

  const profileRows = profiles
    .map(
      (profile) =>
        `| ${code(profile.id)} | ${escapeMarkdown(profile.label)} | ${code(profile.mode)} | ${escapeMarkdown(profile.viewport)} | ${profile.required ? "yes" : "no"} |`,
    )
    .join("\n");

  const targetRows = targets
    .map(
      (target) =>
        `| ${escapeMarkdown(target.label)} | ${code(target.slug)} | ${code(target.activeSurface)} | ${target.activeNavigationId ? code(target.activeNavigationId) : "-"} | ${code(`${target.shellSelector} ${target.targetSelector}`)} | ${target.requiredProfiles.map(code).join("<br>")} |`,
    )
    .join("\n");

  const checklistRows = targets
    .flatMap((target) =>
      target.requiredProfiles.map((profileId) => {
        const profile = profileById.get(profileId);
        const profileLabel = profile ? profile.label : profileId;
        return `| ${escapeMarkdown(target.label)} | ${escapeMarkdown(profileLabel)} | ${code(target.slug)} | ${code(`${target.shellSelector} ${target.targetSelector}`)} | Pending | |`;
      }),
    )
    .join("\n");

  return `# OrbitFabric Studio Visual QA Capture Checklist

Generated from: ${code("src/devSurfaceCaptureManifest.ts")}
Manifest version: ${code(version)}
Generated at: ${generatedAt}

> This file is generated by ${code("npm run qa:visual-checklist")}. Do not edit the checklist tables manually; update the manifest or generator instead.

---

## Purpose

This checklist makes the dev-only Studio visual QA capture process repeatable.

It does not automate screenshot comparison. It defines which surfaces must be captured, under which desktop profiles, and which selectors must remain stable.

---

## Capture Profiles

| Profile id | Label | Mode | Viewport | Required |
| --- | --- | --- | --- | --- |
${profileRows}

---

## Capture Targets

| Surface | Slug | Active surface | Active navigation | Capture selector | Required profiles |
| --- | --- | --- | --- | --- | --- |
${targetRows}

---

## Manual Capture Checklist

Run Studio with:

${code("VITE_OF_DEV_CAPTURE=1 npm run tauri:dev")}

For fullscreen profiles, make the app fullscreen manually and then press ${code("SURFACE")}.

| Surface | Profile | Expected filename slug | Expected target selector | Result | Notes |
| --- | --- | --- | --- | --- | --- |
${checklistRows}

---

## Acceptance Criteria

A visual QA pass is acceptable when:

- every listed capture resolves to the expected surface slug;
- no required public surface falls back to ${code("active-surface")};
- the overlay target selector matches the manifest selector;
- the sidebar state is visible in the overlay;
- the captured content dimensions are plausible for the selected viewport;
- Mission Overview and Core Report Runner remain the golden candidates;
- generated PNG evidence remains local and is not committed.
`;
}

const version = extractManifestVersion(manifestSource);
const profiles = evaluateArrayLiteral(
  extractExportedConstArray(manifestSource, "DEV_SURFACE_CAPTURE_PROFILES"),
  "DEV_SURFACE_CAPTURE_PROFILES",
);
const targets = evaluateArrayLiteral(
  extractExportedConstArray(manifestSource, "DEV_SURFACE_CAPTURE_TARGETS"),
  "DEV_SURFACE_CAPTURE_TARGETS",
);

if (!Array.isArray(profiles) || profiles.length === 0) {
  throw new Error("No capture profiles found.");
}

if (!Array.isArray(targets) || targets.length === 0) {
  throw new Error("No capture targets found.");
}

for (const target of targets) {
  if (!target.label || !target.slug || !target.activeSurface || !target.shellSelector || !target.targetSelector) {
    throw new Error(`Invalid capture target entry: ${JSON.stringify(target)}`);
  }

  if (!Array.isArray(target.requiredProfiles) || target.requiredProfiles.length === 0) {
    throw new Error(`Capture target has no required profiles: ${target.label}`);
  }
}

const rendered = renderChecklist({ version, profiles, targets });

if (shouldCheck) {
  const current = existsSync(checklistPath) ? readFileSync(checklistPath, "utf8") : "";
  if (current !== rendered) {
    throw new Error(`${path.relative(repoRoot, checklistPath)} is out of date. Run npm run qa:visual-checklist.`);
  }
} else if (shouldWrite || args.size === 0) {
  mkdirSync(path.dirname(checklistPath), { recursive: true });
  writeFileSync(checklistPath, rendered, "utf8");
}

console.log(`[visual-qa] profiles: ${profiles.length}`);
console.log(`[visual-qa] targets: ${targets.length}`);
console.log(`[visual-qa] checklist: ${path.relative(repoRoot, checklistPath)}`);
